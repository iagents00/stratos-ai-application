import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';

const org = '10000000-0000-4000-8000-000000000001';
const otherOrg = '10000000-0000-4000-8000-000000000002';
const user = '20000000-0000-4000-8000-000000000001';
const other = '20000000-0000-4000-8000-000000000002';
const task = '30000000-0000-4000-8000-000000000001';
const lead = '40000000-0000-4000-8000-000000000001';

test('Copilot follow-ups use durable three-minute cycles, explicit acknowledgements and per-person preferences', async t => {
  const db = new PGlite();
  const one = async (sql, params = []) => (await db.query(sql, params)).rows[0];
  let base;
  const at = minutes => new Date(base + minutes * 60000).toISOString();
  const tick = async minutes => (await one('select fn_copilot_followup_tick($1) result', [at(minutes)])).result;
  const state = async id => one('select * from copilot_reminder_followups where id=$1', [id]);
  const reset = async () => {
    await db.exec('truncate copilot_reminder_followups,proactive_reminders,tg_bot_activity,proactive_pending_reports,team_actions,mkt_tasks,leads,profiles,organizations,proactive_config,push_test cascade');
    base = new Date((await one('select now() as n')).n).getTime();
    await db.query('insert into organizations(id,meta_config) values($1,$2),($3,$2)', [org, {}, otherOrg]);
    await db.query('insert into profiles(id,organization_id,name,telegram_chat_id) values($1,$2,$3,-123),($4,$5,$6,-456)', [user, org, 'QA Uno', other, otherOrg, 'QA Dos']);
    await db.query('insert into proactive_config(organization_id) values($1),($2)', [org, otherOrg]);
    await db.query("select set_config('test.uid',$1,false)", [user]);
  };
  const remind = async ({ kind = 'personal', payload = { text: 'Enviar reporte' }, owner = user, organization = org, quiet = true, leadId = null, log = true } = {}) => {
    const r = await one("insert into proactive_reminders(organization_id,asesor_id,asesor_name,tipo,payload,ignore_quiet,lead_id,scheduled_at) values($1,$2,'QA Uno',$3,$4,$5,$6,$7) returning id", [organization, owner, kind, payload, quiet, leadId, at(0)]);
    await db.query("update proactive_reminders set status='sent',sent_at=$1 where id=$2", [at(0), r.id]);
    const f = await one("select f.* from copilot_reminder_followups f join proactive_reminders r on r.payload->>'copilot_followup_id'=f.id::text where r.id=$1", [r.id]);
    if (log && f) await db.query("insert into tg_bot_activity(organization_id,telegram_chat_id,role,content,created_at) values($1,$2,'ai',$3,$4)", [organization, owner === user ? -123 : -456, '▸ Recordatorio\n«' + f.title + '»', at(0)]);
    return f;
  };
  try {
    await db.exec(`create role anon; create role authenticated; create role service_role;
      create schema auth;
      create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('test.uid',true),'')::uuid$$;
      grant usage on schema auth to authenticated,anon;
      create table organizations(id uuid primary key,active boolean default true,meta_config jsonb default '{}');
      create table profiles(id uuid primary key,organization_id uuid,name text,telegram_chat_id bigint,active boolean default true,work_tz text,timezone text);
      create table proactive_config(organization_id uuid,enabled boolean default true,timezone text default 'UTC',quiet_start_hour int default 22,quiet_end_hour int default 8,shadow_mode boolean default false,test_asesor_names text[]);
      create table proactive_reminders(id uuid primary key default gen_random_uuid(),organization_id uuid,asesor_id uuid,asesor_name text,tipo text,lead_id uuid,scheduled_at timestamptz default now(),sent_at timestamptz,status text default 'pending',payload jsonb default '{}',dedupe_key text unique,ignore_quiet boolean default false);
      create table proactive_pending_reports(organization_id uuid,reminder_id uuid,status text,kind text,outcome text);
      create table team_actions(id uuid primary key,organization_id uuid,text text,due_at timestamptz,asesor_id uuid,done boolean default false,last_response_at timestamptz,evidence_at timestamptz);
      create table mkt_tasks(id uuid primary key,organization_id uuid,titulo text,due_at timestamptz,assignee_id uuid,estado text default 'por_hacer',deleted_at timestamptz);
      create table leads(id uuid primary key,organization_id uuid,name text,next_action_at timestamptz,visita_at timestamptz,stage text,asesor_id uuid,deleted_at timestamptz);
      create table tg_bot_activity(id bigint generated by default as identity primary key,organization_id uuid,telegram_chat_id bigint,role text,content text,created_at timestamptz default now(),meta jsonb default '{}');
      create table front_rpc_registry(nombre text primary key,nota text);
      create function _bot_agenda_norm(p_text text) returns text language sql immutable as $$select btrim(regexp_replace(translate(lower(coalesce(p_text,'')),'áéíóúñ','aeioun'),'\\s+',' ','g'))$$;
      create function fn_mkt_in_window(p_profile uuid,p_at timestamptz default now()) returns boolean language sql stable as $$select extract(hour from p_at at time zone 'UTC') between 8 and 21$$;
      create table push_test(reminder_id uuid);
      create function push_test_fn() returns trigger language plpgsql as $$begin if new.status='sent' and old.status<>'sent' then insert into push_test values(new.id); end if; return new; end$$;
      create trigger push_test after update on proactive_reminders for each row execute function push_test_fn();
      create function fn_mkt_persecucion_tick() returns jsonb language plpgsql as $$begin return (select jsonb_build_object('intento',x.intento) from(select case when false then 2
                else 0 end as intento) x); end$$;`);
    const migration = readFileSync('supabase/migrations/291_copilot_reminder_followups.sql', 'utf8');
    await db.exec(migration);
    await db.exec(migration);

    await t.test('intense mode repeats at three minutes, continues beyond two, and emits one push per message', async () => {
      await reset();
      const f = await remind();
      assert.equal((await tick(2.99)).sent, 0);
      for (const minute of [3, 6, 9, 12]) {
        assert.deepEqual(await tick(minute), { ok: true, sent: 1, failures: 0 });
        assert.equal((await tick(minute)).sent, 0);
      }
      assert.equal((await state(f.id)).repeat_count, 4);
      assert.equal((await one('select count(*)::int n from push_test')).n, 5);
      assert.equal((await one("select count(*)::int n from tg_bot_activity where meta->>'kind'='copilot_followup'")).n, 4);
      assert.equal((await tick(300)).sent, 1); // One fresh warning, never a catch-up burst.
      assert.equal((await tick(300)).sent, 0);
    });

    await t.test('reduced mode sends at most two additional warnings; switching mode preserves the count', async () => {
      await reset();
      await db.query('select copilot_reminder_settings(false)');
      const f = await remind();
      assert.equal((await tick(3)).sent, 1);
      assert.equal((await tick(6)).sent, 1);
      assert.equal((await tick(9)).sent, 0);
      assert.equal((await state(f.id)).next_followup_at, null);
      await db.query('select copilot_reminder_settings(true)');
      assert.equal((await tick(8.99)).sent, 0);
      assert.equal((await tick(9)).sent, 1);
      await db.query('select copilot_reminder_settings(false)');
      assert.equal((await tick(12)).sent, 0);
      assert.equal((await state(f.id)).repeat_count, 3);
    });

    await t.test('confirming or declining stops the correct cycle without completing the task', async () => {
      for (const [text, response] of [['Te confirmo que lo voy a hacer', 'will_do'], ['No voy a poder', 'unavailable']]) {
        await reset();
        await db.query('insert into team_actions(id,organization_id,text,due_at,asesor_id) values($1,$2,$3,$4,$5)', [task, org, 'Preparar propuesta', at(60), user]);
        const f = await remind({ kind: 'team_action', payload: { action_id: task, text: 'Preparar propuesta', fase: '0' } });
        const reply = (await one('select copilot_reminder_reply($1) result', [text])).result;
        assert.equal(reply.handled, true);
        assert.equal(reply.persisted, true);
        assert.equal((await state(f.id)).response_kind, response);
        const repeated=(await one("select copilot_reminder_reply('Lo voy a hacer',$1,'will_do') result",[f.id])).result;
        assert.match(repeated.reply,/ya tiene una respuesta/);
        assert.equal((await state(f.id)).response_kind,response);
        assert.equal((await one('select done from team_actions where id=$1', [task])).done, false);
        assert.equal((await tick(3)).sent, 0);
        // A later scheduled warning for the same event must not restart the answered cycle.
        await remind({ kind: 'team_action', payload: { action_id: task, text: 'Preparar propuesta', fase: '10' } });
        assert.equal((await one('select count(*)::int n from copilot_reminder_followups')).n, 1);
        assert.equal((await tick(9)).sent, 0);
      }
    });

    await t.test('generic replies require reminder context; unrelated conversations do not acknowledge it', async () => {
      await reset();
      const f = await remind();
      assert.equal((await one("select copilot_reminder_reply('Muéstrame mis clientes') result")).result.handled, false);
      await db.query("insert into tg_bot_activity(organization_id,telegram_chat_id,role,content,created_at) values($1,-123,'ai','¿Quieres ver el reporte?',$2)", [org, at(.1)]);
      assert.equal((await one("select copilot_reminder_reply('sí') result")).result.handled, false);
      assert.equal((await state(f.id)).status, 'pending');
      await tick(3);
      assert.equal((await one("select copilot_reminder_reply('sí') result")).result.handled, true);
      assert.equal((await tick(6)).sent, 0);
    });

    await t.test('voice transcripts and messages from already-installed apps stop only the referenced latest reminder', async () => {
      await reset();
      const first = await remind({ payload: { text: 'Enviar factura' } });
      const second = await remind({ payload: { text: 'Preparar contrato' } });
      await db.query("insert into tg_bot_activity(organization_id,telegram_chat_id,role,content) values($1,-123,'user','No voy a poder')", [org]);
      assert.equal((await state(first.id)).status, 'pending');
      assert.equal((await state(second.id)).status, 'answered');
      await db.query("insert into tg_bot_activity(organization_id,telegram_chat_id,role,content) values($1,-123,'user','Desactiva la insistencia')", [org]);
      assert.equal((await one('select copilot_reminder_settings() result')).result.enabled, false);
      await tick(3.1); await tick(6.1);
      assert.equal((await tick(9.1)).sent, 0);
      await db.query("insert into tg_bot_activity(organization_id,telegram_chat_id,role,content) values($1,-123,'user','Activa la insistencia')", [org]);
      assert.equal((await tick(9.1)).sent, 1);
    });

    await t.test('Zooms, visits and task reminders are cancelled on reschedule, completion or removal', async () => {
      await reset();
      await db.query('insert into leads(id,organization_id,name,next_action_at,stage,asesor_id) values($1,$2,$3,$4,$5,$6)', [lead,org,'Cliente QA',at(60),'Zoom Agendado',user]);
      const zoom = await remind({ kind: 'zoom_brief', leadId: lead, payload: { zoom_at: at(60) } });
      const sameAppointment = await remind({ kind: 'next_action_3h', leadId: lead, payload: { next_action_at: at(60) } });
      assert.equal(sameAppointment.id, zoom.id);
      await tick(3);
      await db.query('update leads set next_action_at=$1 where id=$2', [at(120),lead]);
      assert.equal((await state(zoom.id)).status, 'cancelled');
      assert.equal((await tick(6)).sent, 0);
      const rescheduled = await remind({ kind: 'zoom_15min', leadId: lead, payload: { zoom_at: at(120) } });
      assert.notEqual(rescheduled.id, zoom.id);
      assert.equal((await tick(3)).sent, 1);
      await db.query('update leads set deleted_at=now() where id=$1', [lead]);
      assert.equal((await state(rescheduled.id)).status, 'cancelled');
      await db.query('insert into team_actions(id,organization_id,text,due_at,asesor_id) values($1,$2,$3,$4,$5)', [task,org,'Llamar al banco',at(30),user]);
      const action = await remind({kind:'team_action',payload:{action_id:task,text:'Llamar al banco'}});
      await db.query('update team_actions set done=true where id=$1',[task]);
      assert.equal((await state(action.id)).status,'cancelled');
      assert.equal((await tick(30)).sent,0);
    });

    await t.test('marketing tasks use the same preference and stop when their status changes', async () => {
      await reset();
      await db.query('insert into mkt_tasks(id,organization_id,titulo,due_at,assignee_id) values($1,$2,$3,$4,$5)',[task,org,'Editar propuesta',at(60),user]);
      const f=await remind({payload:{mkt_task_id:task,text:'Recordatorio de propuesta'}});
      assert.equal((await tick(3)).sent,1);
      await db.query("update mkt_tasks set estado='en_proceso' where id=$1",[task]);
      assert.equal((await state(f.id)).status,'cancelled');
      assert.equal((await tick(6)).sent,0);
      assert.equal((await one('select fn_mkt_persecucion_tick() result')).result.intento,0);
    });

    await t.test('quiet hours pause delivery without accumulating messages; inactive recipients remain silent', async () => {
      await reset();
      const quietAt = new Date(base); quietAt.setUTCHours(23,0,0,0); base=quietAt.getTime();
      const f=await remind({quiet:false});
      assert.equal((await tick(3)).sent,0);
      assert.equal((await state(f.id)).repeat_count,0);
      assert.equal((await tick(9*60)).sent,1);
      assert.equal((await tick(9*60)).sent,0);
      await db.query('update profiles set active=false where id=$1',[user]);
      assert.equal((await tick(9*60+3)).sent,0);
    });

    await t.test('settings and responses are isolated by authenticated person, including foreign IDs', async () => {
      await reset();
      const own=await remind();
      const foreign=await remind({owner:other,organization:otherOrg});
      await db.exec('set role authenticated');
      await assert.rejects(db.query('select * from copilot_reminder_followups'),{code:'42501'});
      await assert.rejects(db.query("select copilot_reminder_reply('Lo voy a hacer',$1,'will_do')",[foreign.id]),{code:'42501'});
      await assert.rejects(db.query('select fn_copilot_followup_tick()'),{code:'42501'});
      assert.equal((await one("select copilot_reminder_reply('Lo voy a hacer',$1,'will_do') result",[own.id])).result.handled,true);
      await db.query('select copilot_reminder_settings(false)');
      await db.exec('reset role');
      assert.equal((await one('select copilot_insistence_enabled enabled from profiles where id=$1',[other])).enabled,true);
      assert.equal((await state(foreign.id)).status,'pending');
      await db.exec('set role anon');
      for(const sql of ['select copilot_reminder_settings()','select copilot_reminder_reply(\'ok\')','select fn_copilot_followup_tick()']) await assert.rejects(db.query(sql),{code:'42501'});
      await db.exec('reset role');
    });
  } finally { await db.close(); }
});
